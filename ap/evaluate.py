"""Offline benchmark on the full synthetic estate. Writes docs/evaluation.md.

    python -m ap.evaluate
"""
import pathlib
import time

import networkx as nx

from . import estate, graph, normalize
from .normalize import INTERNET


def run(scale=1.0):
    snaps, expected = estate.build(scale)
    w = normalize.merge(snaps)
    t0 = time.perf_counter()
    a = graph.analyze(w)
    t_search = time.perf_counter() - t0
    name = lambda k: w["nodes"][k]["name"]      # noqa: E731
    found = {tuple(name(n) for n in p["nodes"]) for p in a["paths"]}
    recall = [(e["name"], tuple(e["nodes"]) in found) for e in expected]
    g = a["graph"]
    t0 = time.perf_counter()
    unpruned = 0
    for t in graph.targets(w):      # the same search without pruning to internet-reachable ancestors of the target
        if t in g and nx.has_path(g, INTERNET, t):
            for n, _ in enumerate(nx.shortest_simple_paths(g, INTERNET, t, weight="w")):
                unpruned += 1
                if n >= graph.K_PATHS:
                    break
    t_unpruned = time.perf_counter() - t0
    rows = []
    for k in (1, 2, 3, 4, 6, 8, 10):
        t0 = time.perf_counter()
        o = graph.optimize(w, k)
        rows.append({"k": k, "optimizer": o["risk_after"], "ms": round(1000 * (time.perf_counter() - t0)),
                     "cvss": graph.analyze(w, frozenset(graph.baseline_cvss(w, k)))["risk"],
                     "kev_public": graph.analyze(w, frozenset(graph.baseline_kev_public(w, k)))["risk"]})
    on_path = {r for p in a["paths"] for r in p["remediations"] if r.startswith("patch")}
    top100 = graph.baseline_cvss(w, 100)
    return {"world": w, "analysis": a, "recall": recall, "t_search": t_search, "t_unpruned": t_unpruned, "rows": rows,
            "top100_on_path": len(on_path & set(top100)), "patch_on_path": len(on_path), "graph_nodes": g.number_of_nodes(), "graph_edges": g.number_of_edges()}


def report(m):
    w, a = m["world"], m["analysis"]
    pct = lambda x: f"{100 * (a['risk'] - x) / a['risk']:.0f}%"      # noqa: E731
    lines = ["# Evaluation", "",
             f"Generated by `python -m ap.evaluate` on the full synthetic estate: {sum(n['kind'] == 'asset' for n in w['nodes'].values()):,} assets, "
             f"{sum(n['kind'] == 'identity' for n in w['nodes'].values()):,} identities, {len(w['rels']):,} relationships, {len(w['vulns']):,} open findings.",
             "The estate is invented and the attack chains were planted, so this shows the engine recovers what is there and how the prioritization",
             "rules compare on it. It is not a claim about any real environment.", "",
             "## 1. Seeded attack chains recovered", "",
             f"{sum(ok for _, ok in m['recall'])} of {len(m['recall'])} planted chains were found, node for node.", "", "| Scenario | Found |", "|---|---|"]
    lines += [f"| {n} | {'yes' if ok else 'NO'} |" for n, ok in m["recall"]]
    lines += ["", "## 2. Which fixes to do first", "",
              f"Estate risk index before any fix: {a['risk']} ({a['exposed_targets']} of {len(a['by_target'])} crown jewels reachable, {len(a['paths'])} paths).",
              "Risk remaining after k fixes (lower is better), each verified by re-running the search on the changed graph:", "",
              "| Fixes | Optimizer (max-coverage over paths) | Highest CVSS first | Internet-facing, known-exploited first | Optimizer solve + verify |", "|---|---|---|---|---|"]
    lines += [f"| {r['k']} | {r['optimizer']} ({pct(r['optimizer'])} removed) | {r['cvss']} ({pct(r['cvss'])}) | {r['kev_public']} ({pct(r['kev_public'])}) | {r['ms']} ms |" for r in m["rows"]]
    lines += ["", f"Why severity-first does nothing here: among the 100 highest-CVSS findings in the estate, the number on an attack path to a crown jewel is {m['top100_on_path']}.",
              f"Only {m['patch_on_path']} findings out of {len(w['vulns']):,} are on any such path; the rest are on workloads that lead nowhere critical.",
              "The estate was built with that property on purpose (it is the premise of the product), so the size of the gap is by construction.", "",
              "## 3. Search cost", "",
              f"The attack graph has {m['graph_nodes']:,} nodes and {m['graph_edges']:,} edges after dropping steps that are not exploitable.", "",
              "| Search | Time for all crown jewels |", "|---|---|",
              f"| Pruned to internet-reachable ancestors of each target (what runs) | {1000 * m['t_search']:.0f} ms |",
              f"| k-shortest simple paths on the whole graph | {1000 * m['t_unpruned']:.0f} ms |", "",
              "## Scoring is a stated prior, not a fitted model", "",
              "Step probabilities (for example 0.9 for a permission the attacker already holds, an exploit probability built from CVSS, exploit maturity and",
              "the known-exploited flag) are assumptions written down in `ap/graph.py`. There is no incident history here to calibrate them against,",
              "so risk scores rank paths; they are not probabilities of breach."]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    out = pathlib.Path(__file__).resolve().parent.parent / "docs" / "evaluation.md"
    out.write_text(report(run()))
    print(out.read_text())
